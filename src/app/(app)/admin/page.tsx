import Link from "next/link";
import {
  getAllAchievementsWithPlace,
  getAllAttractions,
  getAllHotels,
  getAllPartners,
  getAllUsersForAdmin,
  getRecentCheckIns,
  getRecentItineraries,
} from "@/db/queries";
import { testToolsEnabled } from "@/lib/dev-tools";
import { Alert, Card } from "@/components/ui";

type Tile = { label: string; value: number; href: string; hint?: string };

export default async function AdminDashboard() {
  const [hotels, attractions, partners, achievements, users, itineraries, checkIns] =
    await Promise.all([
      getAllHotels(),
      getAllAttractions(),
      getAllPartners(),
      getAllAchievementsWithPlace(),
      getAllUsersForAdmin(),
      getRecentItineraries(5),
      getRecentCheckIns(5),
    ]);

  const isProductionBuild = process.env.NODE_ENV === "production";

  const placesWith3d =
    hotels.filter((h) => h.modelPath).length +
    attractions.filter((a) => a.modelPath).length +
    partners.filter((p) => p.modelPath).length;

  const tiles: Tile[] = [
    { label: "Hotels", value: hotels.length, href: "/admin/hotels" },
    { label: "Attractions", value: attractions.length, href: "/admin/attractions" },
    { label: "Partners", value: partners.length, href: "/admin/partners" },
    { label: "Achievements", value: achievements.length, href: "/admin/achievements" },
    { label: "3D models", value: placesWith3d, href: "/admin/models" },
    { label: "Users", value: users.length, href: "/admin/users" },
  ];

  // Anything missing a badge earns nothing when a guest checks in there.
  const placesWithoutAchievement = [
    ...hotels.map((h) => ({ type: "hotel" as const, id: h.id, name: h.name })),
    ...attractions.map((a) => ({ type: "attraction" as const, id: a.id, name: a.name })),
    ...partners.map((p) => ({ type: "partner" as const, id: p.id, name: p.name })),
  ].filter(
    (place) =>
      !achievements.some(
        (achievement) =>
          achievement.placeType === place.type && achievement.placeId === place.id,
      ),
  );

  return (
    <div className="space-y-5">
      <div>
        <h1 className="text-2xl font-semibold">Dashboard</h1>
        <p className="text-sm text-zinc-500">
          Everything guests see is managed from here.
        </p>
      </div>

      {testToolsEnabled() && (
        <Alert kind="warning">
          Testing shortcuts are enabled
          {isProductionBuild
            ? " on this deployment, because ALLOW_TEST_TOOLS_IN_PRODUCTION is set. Unset it to turn them off."
            : " for local development. They are refused in a production build unless deliberately allowed."}{" "}
          Each one only affects the signed-in account.
        </Alert>
      )}

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
        {tiles.map((tile) => (
          <Link
            key={tile.href}
            href={tile.href}
            className="rounded-2xl border border-zinc-200 bg-white p-4 transition hover:border-indigo-400 dark:border-zinc-800 dark:bg-zinc-900"
          >
            <p className="text-2xl font-semibold">{tile.value}</p>
            <p className="text-sm text-zinc-500">{tile.label}</p>
          </Link>
        ))}
      </div>

      {placesWithoutAchievement.length > 0 && (
        <Card
          title="Places without an achievement"
          description="Guests who check in here won't earn a badge until one is added."
        >
          <ul className="flex flex-wrap gap-2">
            {placesWithoutAchievement.slice(0, 12).map((place) => (
              <li key={`${place.type}-${place.id}`}>
                <Link
                  href={`/admin/${place.type}s/${place.id}`}
                  className="rounded-lg border border-amber-300 px-2.5 py-1 text-xs text-amber-800 hover:bg-amber-50 dark:border-amber-800 dark:text-amber-300 dark:hover:bg-amber-950/40"
                >
                  {place.name}
                </Link>
              </li>
            ))}
            {placesWithoutAchievement.length > 12 && (
              <li className="self-center text-xs text-zinc-500">
                +{placesWithoutAchievement.length - 12} more
              </li>
            )}
          </ul>
        </Card>
      )}

      <div className="grid gap-5 lg:grid-cols-2">
        <Card
          title="Recent day plans"
          description="The latest itineraries generated by guests."
          actions={
            <Link href="/admin/itineraries" className="text-sm text-indigo-600 hover:underline">
              See all
            </Link>
          }
        >
          {itineraries.length === 0 ? (
            <p className="text-sm text-zinc-500">No itineraries yet.</p>
          ) : (
            <ul className="space-y-2 text-sm">
              {itineraries.map((row) => (
                <li key={row.dayId} className="flex items-center justify-between gap-3">
                  <span className="truncate">
                    {row.username} · {row.hotelName}
                  </span>
                  <span className="shrink-0 text-xs text-zinc-500">
                    Day {row.dayNumber} · {row.visitedCount}/{row.stopCount}
                  </span>
                </li>
              ))}
            </ul>
          )}
        </Card>

        <Card
          title="Recent check-ins"
          actions={
            <Link href="/admin/check-ins" className="text-sm text-indigo-600 hover:underline">
              See all
            </Link>
          }
        >
          {checkIns.length === 0 ? (
            <p className="text-sm text-zinc-500">No check-ins yet.</p>
          ) : (
            <ul className="space-y-2 text-sm">
              {checkIns.map((row) => (
                <li
                  key={`${row.username}-${row.placeType}-${row.placeId}`}
                  className="flex items-center justify-between gap-3"
                >
                  <span className="min-w-0 truncate">
                    {row.username} ·{" "}
                    <span className="text-zinc-500">
                      {row.placeName ?? "deleted place"}
                    </span>
                  </span>
                  <span className="shrink-0 text-xs text-zinc-500">
                    {row.verificationMode.toUpperCase()} ·{" "}
                    {row.lastCheckedInAt.toLocaleDateString()}
                  </span>
                </li>
              ))}
            </ul>
          )}
        </Card>
      </div>
    </div>
  );
}
