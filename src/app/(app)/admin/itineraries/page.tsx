import { getRecentItineraries } from "@/db/queries";
import { Badge, Card } from "@/components/ui";

export default async function AdminItinerariesPage() {
  const itineraries = await getRecentItineraries(100);

  return (
    <Card title="Itineraries" description="Day plans generated by guests, newest first.">
      {itineraries.length === 0 ? (
        <p className="text-sm text-zinc-500">No day plans yet.</p>
      ) : (
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="text-xs uppercase tracking-wide text-zinc-400">
              <tr>
                <th className="py-2 pr-3">Guest</th>
                <th className="py-2 pr-3">Hotel</th>
                <th className="py-2 pr-3">Day</th>
                <th className="py-2 pr-3">Progress</th>
                <th className="py-2 pr-3">Generated</th>
                <th className="py-2 pr-3">Status</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-zinc-200 dark:divide-zinc-800">
              {itineraries.map((row) => (
                <tr key={row.dayId}>
                  <td className="py-2.5 pr-3 font-medium">{row.username}</td>
                  <td className="py-2.5 pr-3 text-zinc-500">{row.hotelName}</td>
                  <td className="py-2.5 pr-3 text-zinc-500">{row.dayNumber}</td>
                  <td className="py-2.5 pr-3 text-zinc-500">
                    {row.visitedCount}/{row.stopCount}
                  </td>
                  <td className="py-2.5 pr-3 text-zinc-500">
                    {row.generatedAt.toLocaleString()}
                  </td>
                  <td className="py-2.5 pr-3">
                    {row.completedAt ? (
                      <Badge tone="green">Complete</Badge>
                    ) : (
                      <Badge>In progress</Badge>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </Card>
  );
}
